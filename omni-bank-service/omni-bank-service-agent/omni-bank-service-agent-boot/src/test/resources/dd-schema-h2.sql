-- H2 集成测试专用表结构：语义与 docs/sql/omni_bank_dd.sql 一致，方言差异（JSON/TIMESTAMP(3)/ENGINE）在测试库中简化
CREATE TABLE IF NOT EXISTS dd_task (
    id                 BIGINT       NOT NULL PRIMARY KEY,
    task_no            VARCHAR(40)  NOT NULL,
    enterprise_id      BIGINT       NOT NULL,
    application_id     BIGINT,
    task_name          VARCHAR(200),
    task_status        VARCHAR(40)  NOT NULL,
    current_stage      VARCHAR(40),
    current_plan_id    BIGINT,
    context_version    INT          DEFAULT 1,
    analysis_version   INT          DEFAULT 0,
    last_error_code    VARCHAR(64),
    last_error_message VARCHAR(1000),
    submitted_at       TIMESTAMP,
    completed_at       TIMESTAMP,
    creator            VARCHAR(64),
    create_time        TIMESTAMP,
    updater            VARCHAR(64),
    update_time        TIMESTAMP,
    version            INT          DEFAULT 0,
    del_flag           TINYINT      DEFAULT 0,
    CONSTRAINT uk_dd_task_no UNIQUE (task_no)
);

CREATE TABLE IF NOT EXISTS dd_enterprise (
    id                 BIGINT        NOT NULL PRIMARY KEY,
    customer_id        VARCHAR(64),
    credit_code        VARCHAR(32)   NOT NULL,
    enterprise_name    VARCHAR(256)  NOT NULL,
    legal_person       VARCHAR(128),
    registered_address VARCHAR(500),
    business_scope     VARCHAR(4000),
    registered_capital DECIMAL(20, 2),
    establishment_date DATE,
    business_status    VARCHAR(64),
    industry_code      VARCHAR(64),
    industry_name      VARCHAR(128),
    enterprise_profile VARCHAR(4000),
    data_source        VARCHAR(64),
    last_sync_at       TIMESTAMP,
    creator            VARCHAR(64),
    create_time        TIMESTAMP,
    updater            VARCHAR(64),
    update_time        TIMESTAMP,
    version            INT           DEFAULT 0,
    del_flag           TINYINT       DEFAULT 0,
    CONSTRAINT uk_dd_enterprise_credit_code UNIQUE (credit_code)
);

CREATE TABLE IF NOT EXISTS dd_loan_application (
    id                   BIGINT        NOT NULL PRIMARY KEY,
    task_id              BIGINT        NOT NULL,
    application_no       VARCHAR(64),
    application_type     VARCHAR(64),
    product_code         VARCHAR(64),
    product_name         VARCHAR(128),
    apply_amount         DECIMAL(20, 2),
    currency             VARCHAR(8),
    apply_term           INT,
    term_unit            VARCHAR(16),
    loan_purpose         VARCHAR(1000),
    repayment_method     VARCHAR(64),
    guarantee_type       VARCHAR(64),
    application_snapshot VARCHAR(4000),
    creator              VARCHAR(64),
    create_time          TIMESTAMP,
    updater              VARCHAR(64),
    update_time          TIMESTAMP,
    version              INT           DEFAULT 0,
    del_flag             TINYINT       DEFAULT 0,
    CONSTRAINT uk_dd_loan_application_task UNIQUE (task_id)
);

CREATE TABLE IF NOT EXISTS dd_business_scenario (
    id                BIGINT       NOT NULL PRIMARY KEY,
    task_id           BIGINT       NOT NULL,
    scenario_version  INT          NOT NULL,
